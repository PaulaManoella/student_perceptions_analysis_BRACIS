input_file = 'all_models_topics.csv'
output_file = 'all_models_topics_en.csv'

with open(input_file, mode='r', encoding='utf-8') as infile, \
     open(output_file, mode='w', newline='', encoding='utf-8') as outfile:
    
    reader = csv.reader(infile)
    writer = csv.writer(outfile)
    
    header = next(reader)
    writer.writerow(header)
    
    for row in reader:
        model = row[0]
        keywords_str = row[1]
        
        try:
            keywords_list = ast.literal_eval(keywords_str)
        except:
            keywords_list = []
            
        translated_list = [translation_dict.get(kw.lower(), kw) for kw in keywords_list]
        
        # Write exactly in the same array string format
        writer.writerow([model, str(translated_list)])

print(f"File saved to {output_file}")
